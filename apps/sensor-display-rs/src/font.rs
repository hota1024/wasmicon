/// 文字から字形の番号へ。対応していない文字は空白。
#[must_use]
pub fn index_of(c: u8) -> usize {
    match c {
        b'-' => 1,
        b'.' => 2,
        b'0'..=b'9' => 3 + (c - b'0') as usize,
        b':' => 13,
        b'%' => 14,
        b'C' => 15,
        b'H' => 16,
        b'T' => 17,
        _ => 0,
    }
}
