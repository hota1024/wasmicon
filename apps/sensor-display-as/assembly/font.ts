/// 文字から字形の番号へ。対応していない文字は空白。
export function indexOf(c: u8): i32 {
  if (c == 0x2d) return 1; // '-'
  if (c == 0x2e) return 2; // '.'
  if (c >= 0x30 && c <= 0x39) return 3 + (c - 0x30); // '0'..'9'
  if (c == 0x3a) return 13; // ':'
  if (c == 0x25) return 14; // '%'
  if (c == 0x43) return 15; // 'C'
  if (c == 0x48) return 16; // 'H'
  if (c == 0x54) return 17; // 'T'
  if (c == 0x41) return 18; // 'A'
  if (c == 0x44) return 19; // 'D'
  if (c == 0x45) return 20; // 'E'
  if (c == 0x49) return 21; // 'I'
  if (c == 0x4d) return 22; // 'M'
  if (c == 0x4e) return 23; // 'N'
  if (c == 0x4f) return 24; // 'O'
  if (c == 0x50) return 25; // 'P'
  if (c == 0x52) return 26; // 'R'
  if (c == 0x53) return 27; // 'S'
  if (c == 0x55) return 28; // 'U'
  if (c == 0x57) return 29; // 'W'
  if (c == 0x59) return 30; // 'Y'
  return 0;
}
