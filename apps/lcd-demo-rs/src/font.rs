/// Maps a character to its glyph index. Unsupported characters map to the
/// space.
#[must_use]
pub fn index_of(c: u8) -> usize {
    match c {
        b'-' => 1,
        b'.' => 2,
        b'0'..=b'9' => 3 + (c - b'0') as usize,
        b':' => 13,
        b'%' => 14,
        b'!' => 15,
        b'A'..=b'Z' => 16 + (c - b'A') as usize,
        _ => 0,
    }
}
