//!
//! ファームにアプリは入っていないので、スロットが空・壊れているときは
//! 理由をシリアルに出したあとここに来る。**ピンは何も駆動しない**
//! （2026-10-07 オーナー決定。役割名はファームの語彙ではないので、
//! 「生存確認の LED」のような特別なピンを持たない）。

use crate::Board;

/// 待ち続ける。戻らない。
pub fn park<B: Board>(board: &mut B) -> ! {
    loop {
        board.sleep_ms(1000);
    }
}
